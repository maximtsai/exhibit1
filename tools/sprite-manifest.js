// Generates scripts/spritemanifest.js: the list of PNGs in each raw/ sprite folder.
// Browsers can't list a folder, so the game reads this to know which frames to load.
//
//   node tools/sprite-manifest.js        (rewrites scripts/spritemanifest.js)
//
// You rarely need to run it by hand: build.js regenerates it before bundling, and
// tools/devserver.js serves a freshly generated copy on every page load, so a new
// PNG dropped into a raw/ folder shows up on refresh.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const outFile = path.join(root, "scripts", "spritemanifest.js");

// Folders holding single images loaded by path (see config.js), not sprite sheets
const NOT_SHEETS = new Set(["standalone"]);

function buildManifestSource() {
    const rawDir = path.join(root, "raw");
    const folders = fs.readdirSync(rawDir, { withFileTypes: true })
        .filter((d) => d.isDirectory() && !NOT_SHEETS.has(d.name))
        .map((d) => d.name)
        .sort();
    let src = "// Generated by tools/sprite-manifest.js from the PNGs in raw/. Don't edit by hand:\n" +
        "// add, remove or rename files in raw/ instead (see tools/README.md).\n" +
        "// Each sheet folder's frames are named after its files, without \".png\".\n" +
        "const SPRITE_MANIFEST = {\n";
    folders.forEach((folder, i) => {
        const frames = fs.readdirSync(path.join(rawDir, folder))
            .filter((f) => f.toLowerCase().endsWith(".png"))
            .map((f) => f.slice(0, -4))
            .sort();
        src += "    " + JSON.stringify("raw/" + folder) + ": [\n" +
            frames.map((f) => "        " + JSON.stringify(f)).join(",\n") +
            "\n    ]" + (i < folders.length - 1 ? "," : "") + "\n";
    });
    return src + "};\n";
}

function writeManifest() {
    const src = buildManifestSource();
    const old = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : null;
    if (old !== src) fs.writeFileSync(outFile, src);
    return old !== src;
}

module.exports = { buildManifestSource, writeManifest };

if (require.main === module) {
    console.log(writeManifest() ? "Updated scripts/spritemanifest.js" : "scripts/spritemanifest.js already up to date");
}
